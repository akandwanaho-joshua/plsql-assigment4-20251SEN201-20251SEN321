-- Run using F5 in a dedicated Oracle schema.
CREATE TABLE a4_students (
 student_id NUMBER(6) CONSTRAINT a4_students_pk PRIMARY KEY,
 full_name VARCHAR2(100) NOT NULL,
 email VARCHAR2(120) CONSTRAINT a4_students_email_uq UNIQUE,
 created_at DATE DEFAULT SYSDATE NOT NULL
);
CREATE TABLE a4_courses (
 course_id NUMBER(6) CONSTRAINT a4_courses_pk PRIMARY KEY,
 course_name VARCHAR2(100) NOT NULL,
 credits NUMBER(2) CONSTRAINT a4_credits_ck CHECK (credits BETWEEN 1 AND 6)
);
CREATE TABLE a4_enrollments (
 enrollment_id NUMBER(6) CONSTRAINT a4_enroll_pk PRIMARY KEY,
 student_id NUMBER(6) NOT NULL CONSTRAINT a4_enroll_student_fk REFERENCES a4_students(student_id),
 course_id NUMBER(6) NOT NULL CONSTRAINT a4_enroll_course_fk REFERENCES a4_courses(course_id),
 grade NUMBER(5,2) CONSTRAINT a4_grade_ck CHECK (grade BETWEEN 0 AND 100),
 CONSTRAINT a4_enroll_unique UNIQUE(student_id,course_id)
);
CREATE TABLE a4_grade_audit (
 audit_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT a4_audit_pk PRIMARY KEY,
 enrollment_id NUMBER(6) NOT NULL,
 old_grade NUMBER(5,2), new_grade NUMBER(5,2), changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);